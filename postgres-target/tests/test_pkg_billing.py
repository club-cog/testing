"""Behaviour of the converted PKG_BILLING functions."""

from __future__ import annotations

import psycopg
import pytest
from conftest import dec, one, rows, scalar


def test_issue_invoice_creates_issued_invoice(cur):
    """Covers DUAL removal, sequence reuse, SYSDATE + 30 and the CLOB note."""
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(5002)")
    number, status, total, tax, issued, due, note = one(
        cur,
        "SELECT invoice_number, invoice_status, invoice_total, tax_total,"
        " issued_on, due_on, delivery_note"
        " FROM retail.invoices WHERE invoice_id = %s",
        (invoice_id,),
    )
    assert number == f"INV-{invoice_id}"
    assert status == "ISSUED"
    assert total == 0, "order 5002 totals zero because its only line has no amount"
    assert tax == 0
    assert (due - issued).days == 30
    assert note == "Generated by legacy billing batch"


def test_issue_invoice_carries_order_total_and_tax(cur):
    order_id = scalar(cur, "SELECT pkg_order_mgmt.create_order('ORD-B001', 1001, NULL)")
    cur.execute("SELECT pkg_order_mgmt.add_order_line(%s, 3003, 1, 100.00)", (order_id,))
    order_total = scalar(
        cur, "SELECT total_amount FROM retail.orders WHERE order_id = %s", (order_id,)
    )
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(%s)", (order_id,))
    total, tax = one(
        cur,
        "SELECT invoice_total, tax_total FROM retail.invoices WHERE invoice_id = %s",
        (invoice_id,),
    )
    assert total == order_total == dec("108.25")
    assert tax == dec("8.93"), "round(108.25 * 0.0825, 2)"


def test_issue_invoice_writes_audit_row_and_sets_run_label(cur):
    """Autonomous transaction logging, now inside the caller's transaction."""
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(5002)")
    assert scalar(cur, "SELECT pkg_billing.g_run_label()") == f"INV-{invoice_id}"

    entity, action, payload, actor = one(
        cur,
        "SELECT entity_name, action_code, payload, actor_name FROM retail.audit_log"
        " WHERE entity_id = %s AND action_code = 'ISSUED'",
        (invoice_id,),
    )
    assert (entity, action, payload) == ("INVOICE", "ISSUED", f"INV-{invoice_id}")
    assert actor, "SYS_CONTEXT session user became session_user"


def test_billing_log_rolls_back_with_caller_unlike_autonomous_transaction(conn, cur):
    """Deliberate difference. Oracle committed the log row independently."""
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(5002)")
    assert scalar(
        cur, "SELECT count(*) FROM retail.audit_log WHERE entity_id = %s", (invoice_id,)
    ) == 1
    conn.rollback()
    assert scalar(
        cur, "SELECT count(*) FROM retail.audit_log WHERE entity_id = %s", (invoice_id,)
    ) == 0


def test_write_billing_log_swallows_its_own_failure(cur):
    """The Oracle handler was WHEN OTHERS THEN ROLLBACK; NULL. A logging failure
    must not reach the caller. action_code is varchar(20) here, so an oversized
    value fails inside the function."""
    before = scalar(cur, "SELECT count(*) FROM retail.audit_log")
    cur.execute("SELECT pkg_billing.write_billing_log(6001, %s, 'payload')", ("X" * 40,))
    assert scalar(cur, "SELECT count(*) FROM retail.audit_log") == before
    # the session is still usable, which is the point of the handler
    assert scalar(cur, "SELECT 1") == 1


def test_write_billing_log_autonomous_degrades_without_dblink(cur):
    mode = scalar(
        cur, "SELECT pkg_billing.write_billing_log_autonomous(6001, 'PROBE', 'p')"
    )
    assert mode in ("in-transaction", "autonomous")
    assert scalar(
        cur,
        "SELECT count(*) FROM retail.audit_log WHERE entity_id = 6001 AND action_code = 'PROBE'",
    ) == 1


