def test_rebuild_invoice_totals_recomputes_from_lines(cur):
    """BULK COLLECT, the summing FOR loop and FORALL became set based SQL."""
    total = scalar(cur, "SELECT pkg_billing.rebuild_invoice_totals(6001)")
    assert total == dec("119.99")

    invoice_total, tax_total = one(
        cur, "SELECT invoice_total, tax_total FROM retail.invoices WHERE invoice_id = 6001"
    )
    assert invoice_total == dec("119.99")
    assert tax_total == dec("9.90")

    line_taxes = rows(
        cur,
        "SELECT invoice_line_id, tax_amount FROM retail.invoice_lines"
        " WHERE invoice_id = 6001 ORDER BY invoice_line_id",
    )
    assert [(i, float(t)) for i, t in line_taxes] == [(7001, 1.65), (7002, 8.25)]


def test_rebuild_invoice_totals_handles_zero_and_null_amounts(cur):
    """Invoice 6002 has one line with a zero amount."""
    assert scalar(cur, "SELECT pkg_billing.rebuild_invoice_totals(6002)") == 0

    cur.execute(
        "INSERT INTO retail.invoice_lines"
        " (invoice_line_id, invoice_id, order_line_number, quantity, line_amount)"
        " VALUES (nextval('retail.seq_invoice_lines'), 6002, 2, 1, NULL)"
    )
    assert scalar(cur, "SELECT pkg_billing.rebuild_invoice_totals(6002)") == 0
    assert scalar(
        cur,
        "SELECT tax_amount FROM retail.invoice_lines WHERE invoice_id = 6002"
        " AND order_line_number = 2",
    ) == 0


