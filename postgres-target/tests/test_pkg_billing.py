def test_apply_payment_partial_then_paid(cur):
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(5005)")
    total = scalar(
        cur, "SELECT invoice_total FROM retail.invoices WHERE invoice_id = %s", (invoice_id,)
    )
    assert total == dec("27.06")

    assert scalar(
        cur, "SELECT pkg_billing.apply_payment(%s, 10.00, 'CARD')", (invoice_id,)
    ) == "PARTIAL"
    assert scalar(
        cur, "SELECT pkg_billing.apply_payment(%s, 17.06, 'ACH')", (invoice_id,)
    ) == "PAID"
    assert scalar(
        cur, "SELECT invoice_status FROM retail.invoices WHERE invoice_id = %s", (invoice_id,)
    ) == "PAID"

    paid = scalar(
        cur,
        "SELECT SUM(amount_paid) FROM retail.payments WHERE invoice_id = %s",
        (invoice_id,),
    )
    assert paid == dec("27.06")


def test_apply_payment_defaults_unknown_method(cur):
    invoice_id = scalar(cur, "SELECT pkg_billing.issue_invoice(5006)")
    cur.execute("SELECT pkg_billing.apply_payment(%s, 5.00, NULL)", (invoice_id,))
    method, status = one(
        cur,
        "SELECT payment_method, payment_status FROM retail.payments"
        " WHERE invoice_id = %s ORDER BY payment_id DESC LIMIT 1",
        (invoice_id,),
    )
    assert (method, status) == ("UNKNOWN", "CAPTURED")


def test_apply_payment_against_void_invoice_keeps_oracle_behaviour(cur):
    """Source behaviour preserved, including its oddity: the new payment row is
    PENDING because the invoice was VOID, and then the status UPDATE still marks
    the invoice PAID. Flagged for sign off in CONVERSION-NOTES.md."""
    status = scalar(cur, "SELECT pkg_billing.apply_payment(6003, 5.00, 'CARD')")
    payment_status = scalar(
        cur,
        "SELECT payment_status FROM retail.payments WHERE invoice_id = 6003"
        " ORDER BY payment_id DESC LIMIT 1",
    )
    assert payment_status == "PENDING"
    assert status == "PAID"


