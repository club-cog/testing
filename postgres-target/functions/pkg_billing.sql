-- Converted from oracle-legacy-estate/packages/pkg_billing.pks / .pkb
--
-- Package becomes schema pkg_billing. Package variable g_run_label becomes a
-- session GUC, same approach and same caveat as pkg_order_mgmt.

CREATE OR REPLACE FUNCTION pkg_billing.g_run_label()
RETURNS text
LANGUAGE sql
AS $$
    SELECT COALESCE(NULLIF(current_setting('pkg_billing.run_label', true), ''), 'UNSET');
$$;

-- write_billing_log ----------------------------------------------------------
--
-- The Oracle procedure is PRAGMA AUTONOMOUS_TRANSACTION with its own COMMIT and
-- a WHEN OTHERS handler that rolls back and swallows the error, so the audit row
-- survives even when the caller later fails.
--
-- PostgreSQL has no autonomous transactions. A plain function cannot COMMIT.
-- Three options were considered:
--
--   1. Plain insert in the caller's transaction. Loses durability on caller
--      rollback. Chosen as the default, because it needs no extension and keeps
--      the log consistent with the data it describes.
--   2. dblink or pg_background loopback connection, which does give a genuinely
--      separate transaction. Needs an extension, a connection string and a
--      security review; offered as write_billing_log_autonomous below, guarded
--      so it degrades to option 1 when dblink is absent.
--   3. A PROCEDURE with COMMIT, callable only with CALL outside a transaction
--      block. Rejected: every caller here is mid-transaction.
--
-- This is the one place in the conversion where behaviour cannot be preserved
-- without an infrastructure decision. Flagged for DBA sign off.
CREATE OR REPLACE FUNCTION pkg_billing.write_billing_log(
    p_entity_id   bigint,
    p_action_code varchar,
    p_payload     text
)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO retail.audit_log (
        audit_id,
        event_time,
        entity_name,
        entity_id,
        action_code,
        actor_name,
        payload
    )
    VALUES (
        nextval('retail.seq_audit_log'),
        retail.sysdate(),
        'INVOICE',
        p_entity_id,
        p_action_code,
        -- SYS_CONTEXT('USERENV','SESSION_USER')
        COALESCE(session_user::text, 'BATCH'),
        p_payload
    );
EXCEPTION
    WHEN OTHERS THEN
        -- Matches the Oracle handler, which swallowed everything. Kept
        -- deliberately: callers must not fail because logging failed.
        NULL;
END;
$$;

CREATE OR REPLACE FUNCTION pkg_billing.write_billing_log_autonomous(
    p_entity_id   bigint,
    p_action_code varchar,
    p_payload     text
)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    l_sql text;
BEGIN
    IF to_regprocedure('public.dblink_exec(text,text)') IS NULL THEN
        PERFORM pkg_billing.write_billing_log(p_entity_id, p_action_code, p_payload);
        RETURN 'in-transaction';
    END IF;

    l_sql := format(
        'INSERT INTO retail.audit_log (audit_id, event_time, entity_name, entity_id,'
        || ' action_code, actor_name, payload) VALUES'
        || ' (nextval(%L), retail.sysdate(), %L, %s, %L, %L, %L)',
        'retail.seq_audit_log', 'INVOICE', p_entity_id::text,
        p_action_code, session_user::text, p_payload);

    EXECUTE format('SELECT public.dblink_exec(%L, %L)',
                   'dbname=' || current_database(), l_sql);
    RETURN 'autonomous';
EXCEPTION
    WHEN OTHERS THEN
        RETURN 'failed';
END;
$$;

-- issue_invoice --------------------------------------------------------------
--
-- Oracle constructs handled here: SELECT ... FROM DUAL, sequence NEXTVAL then
-- CURRVAL reuse, SYSDATE and SYSDATE + 30, DBMS_LOB.CREATETEMPORARY /
-- WRITEAPPEND / ISTEMPORARY / FREETEMPORARY, RETURNING INTO, package state
-- assignment and RAISE_APPLICATION_ERROR(-20911).
--
-- The temporary LOB is gone. In PostgreSQL a CLOB is a text value with no
-- handle to allocate or free, so the three DBMS_LOB calls collapse into one
-- assignment. There is nothing to leak, which also removes the duplicated
-- cleanup in the exception handler.
CREATE OR REPLACE FUNCTION pkg_billing.issue_invoice(p_order_id bigint)
RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
    l_order_total numeric(14, 2);
    l_invoice_seq bigint;
    l_invoice_no  varchar(28);
    l_note        text := 'Generated by legacy billing batch';
    l_invoice_id  bigint;
BEGIN
    SELECT COALESCE(total_amount, 0)
    INTO STRICT l_order_total
    FROM retail.orders
    WHERE order_id = p_order_id;

    -- Oracle called seq_invoices.NEXTVAL for the number and then CURRVAL for
    -- the key. One nextval into a variable is the same value, without relying
    -- on CURRVAL session state.
    l_invoice_seq := nextval('retail.seq_invoices');
    l_invoice_no := 'INV-' || l_invoice_seq::text;

    INSERT INTO retail.invoices (
        invoice_id,
        invoice_number,
        order_id,
        issued_on,
        due_on,
        invoice_status,
        invoice_total,
        tax_total,
        delivery_note
    )
    VALUES (
        l_invoice_seq,
        l_invoice_no,
        p_order_id,
        retail.sysdate(),
        retail.sysdate() + interval '30 days',
        'ISSUED',
        l_order_total,
        round(COALESCE(l_order_total, 0) * 0.0825, 2),
        l_note
    )
    RETURNING invoice_id INTO l_invoice_id;

    PERFORM set_config('pkg_billing.run_label', 'INV-' || l_invoice_id::text, false);
    PERFORM pkg_billing.write_billing_log(l_invoice_id, 'ISSUED', pkg_billing.g_run_label());

    RETURN l_invoice_id;
EXCEPTION
    WHEN no_data_found THEN
        RAISE EXCEPTION 'Invoice creation failed: order % not found', p_order_id
            USING ERRCODE = 'OR911';
    WHEN OTHERS THEN
        RAISE EXCEPTION 'Invoice creation failed: %', SQLERRM USING ERRCODE = 'OR911';
END;
$$;

-- apply_payment --------------------------------------------------------------
--
-- Oracle constructs handled here: SELECT ... FOR UPDATE, DECODE, NVL,
-- NO_DATA_FOUND mapped to a named error, and CASE-driven status update.
--
-- Note that the AFTER INSERT trigger on payments (trg_payments_ai) also touches
-- invoice_status. Order of operations is the same as Oracle: trigger sets
-- PARTIAL, then this function's UPDATE decides PAID or PARTIAL.
--
-- Source Oracle bug preserved: tax_total is excluded from the paid-in-full
-- comparison, so an invoice is marked PAID once invoice_total is covered even
-- though the customer still owes tax_total.
CREATE OR REPLACE FUNCTION pkg_billing.apply_payment(
    p_invoice_id bigint,
    p_amount     numeric,
    p_method     varchar
)
RETURNS varchar
LANGUAGE plpgsql
AS $$
DECLARE
    l_invoice_total numeric(14, 2);
    l_paid_total    numeric(14, 2);
    l_status        varchar(14);
    l_new_status    varchar(14);
BEGIN
    BEGIN
        SELECT invoice_total, invoice_status
        INTO STRICT l_invoice_total, l_status
        FROM retail.invoices
        WHERE invoice_id = p_invoice_id
        FOR UPDATE;
    EXCEPTION
        WHEN no_data_found THEN
            RAISE EXCEPTION 'Invoice does not exist' USING ERRCODE = 'OR912';
    END;

    SELECT COALESCE(SUM(amount_paid), 0)
    INTO l_paid_total
    FROM retail.payments
    WHERE invoice_id = p_invoice_id
      AND payment_status = 'CAPTURED';

    INSERT INTO retail.payments (
        payment_id,
        invoice_id,
        paid_on,
        payment_method,
        payment_status,
        amount_paid
    )
    VALUES (
        nextval('retail.seq_payments'),
        p_invoice_id,
        retail.sysdate(),
        COALESCE(p_method, 'UNKNOWN'),
        CASE WHEN l_status = 'VOID' THEN 'PENDING' ELSE 'CAPTURED' END,
        p_amount
    );

    l_paid_total := COALESCE(l_paid_total, 0) + COALESCE(p_amount, 0);
    l_new_status := CASE
                        WHEN l_paid_total >= COALESCE(l_invoice_total, 0) THEN 'PAID'
                        ELSE 'PARTIAL'
                    END;

    UPDATE retail.invoices
    SET invoice_status = l_new_status
    WHERE invoice_id = p_invoice_id;

    PERFORM pkg_billing.write_billing_log(
        p_invoice_id,
        'PAYMENT',
        'paid=' || p_amount::text || ';method=' || COALESCE(p_method, 'UNKNOWN')
    );

    RETURN l_new_status;
END;
$$;

-- rebuild_invoice_totals -----------------------------------------------------
--
-- Oracle constructs handled here: dynamic SQL with a bind variable, BULK
-- COLLECT INTO two collections, a numeric FOR loop that summed one of them,
-- FORALL UPDATE, and DBMS_OUTPUT reading package state.
--
-- BULK COLLECT plus FORALL exist because PL/SQL row-at-a-time is slow.
-- PostgreSQL does not need either: the sum is an aggregate and the FORALL
-- becomes one correlated UPDATE. The dynamic SQL is kept, since the estate
-- clearly builds statement text at run time elsewhere, but rewritten with
-- format() and %I so the identifier is quoted and the parameter stays bound.
CREATE OR REPLACE FUNCTION pkg_billing.rebuild_invoice_totals(p_invoice_id bigint)
RETURNS numeric
LANGUAGE plpgsql
AS $$
DECLARE
    l_sql   text;
    l_total numeric(14, 2);
BEGIN
    l_sql := format(
        'SELECT COALESCE(SUM(COALESCE(line_amount, 0)), 0) FROM %I.%I WHERE invoice_id = $1',
        'retail', 'invoice_lines');
    EXECUTE l_sql INTO l_total USING p_invoice_id;

    UPDATE retail.invoice_lines
    SET tax_amount = round(COALESCE(line_amount, 0) * 0.0825, 2)
    WHERE invoice_id = p_invoice_id;

    UPDATE retail.invoices
    SET invoice_total = l_total,
        tax_total = round(l_total * 0.0825, 2)
    WHERE invoice_id = p_invoice_id;

    RAISE NOTICE 'rebuilt % total=%', pkg_billing.g_run_label(), l_total;
    RETURN l_total;
END;
$$;
