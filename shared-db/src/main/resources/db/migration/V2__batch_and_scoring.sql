-- 2012-03: nightly CAIS-style ingest and score persistence (project ATLAS)
CREATE SEQUENCE BATCH_SEQ START WITH 9000;
CREATE SEQUENCE BATCH_REJ_SEQ START WITH 1;
CREATE SEQUENCE SCR_HIST_SEQ START WITH 1;

CREATE TABLE BATCH_RUN_LOG (
    BATCH_ID        BIGINT       NOT NULL,
    FILE_NM         VARCHAR(200) NOT NULL,
    SRC_LNDR_REF_CD CHAR(6),
    START_TS        TIMESTAMP    NOT NULL,
    END_TS          TIMESTAMP,
    REC_READ        INTEGER      DEFAULT 0,
    REC_LOADED      INTEGER      DEFAULT 0,
    REC_REJECTED    INTEGER      DEFAULT 0,
    STS_CD          VARCHAR(10)  NOT NULL,
    CONSTRAINT PK_BATCH_RUN_LOG PRIMARY KEY (BATCH_ID)
);

CREATE TABLE BATCH_REJECT (
    REJ_ID          BIGINT       NOT NULL,
    BATCH_ID        BIGINT       NOT NULL,
    LINE_NO         INTEGER      NOT NULL,
    RAW_REC         VARCHAR(400),
    RJCT_RSN        VARCHAR(200) NOT NULL,
    CONSTRAINT PK_BATCH_REJECT PRIMARY KEY (REJ_ID),
    CONSTRAINT FK_REJ_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCH_RUN_LOG (BATCH_ID)
);

CREATE TABLE SCORE_MODEL_PARAM (
    MODEL_VER       VARCHAR(8)   NOT NULL,
    PARAM_CD        VARCHAR(30)  NOT NULL,
    PARAM_VAL       INTEGER      NOT NULL,
    CONSTRAINT PK_SCORE_MODEL_PARAM PRIMARY KEY (MODEL_VER, PARAM_CD)
);

CREATE TABLE SCORE_HISTORY (
    SCR_HIST_ID     BIGINT       NOT NULL,
    CNSMR_ID        BIGINT       NOT NULL,
    SCR_VAL         INTEGER,
    SCR_BAND_CD     VARCHAR(10)  NOT NULL,
    MODEL_VER       VARCHAR(8)   NOT NULL,
    AS_OF_DT        DATE         NOT NULL,
    CALC_TS         TIMESTAMP    NOT NULL,
    TRIGGER_CD      VARCHAR(20)  NOT NULL,   -- BATCH, DISPUTE_OPEN, DISPUTE_CLOSE, ADHOC
    RSN_CDS         VARCHAR(200),
    CONSTRAINT PK_SCORE_HISTORY PRIMARY KEY (SCR_HIST_ID),
    CONSTRAINT FK_SCRH_CNSMR FOREIGN KEY (CNSMR_ID) REFERENCES CONSUMER (CNSMR_ID)
);
CREATE INDEX IX_SCRH_CNSMR ON SCORE_HISTORY (CNSMR_ID);
