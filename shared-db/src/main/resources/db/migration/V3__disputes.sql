-- 2013-09: Disputes moved off the Lotus Notes app into the platform.
CREATE SEQUENCE DSPT_SEQ START WITH 40000;
CREATE SEQUENCE DSPT_EVT_SEQ START WITH 1;
CREATE SEQUENCE CORR_SEQ START WITH 1;

CREATE TABLE OPERATOR (
    OPR_ID          VARCHAR(8)   NOT NULL,
    OPR_NM          VARCHAR(80)  NOT NULL,
    TEAM_CD         VARCHAR(10)  NOT NULL,
    ACTV_FLG        CHAR(1)      DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_OPERATOR PRIMARY KEY (OPR_ID)
);

CREATE TABLE BANK_HOLIDAY (
    HOL_DT          DATE         NOT NULL,
    REGION_CD       CHAR(2)      NOT NULL,   -- EW = England & Wales, SC = Scotland, NI = Northern Ireland
    HOL_NM          VARCHAR(60)  NOT NULL,
    CONSTRAINT PK_BANK_HOLIDAY PRIMARY KEY (HOL_DT, REGION_CD)
);

-- TRDLN_ID is nullable: a dispute can be about a public record instead.
-- PUB_REC_ID deliberately has no FK (public records get re-keyed by the Registry reload).
CREATE TABLE DISPUTE_CASE (
    DSPT_ID         BIGINT       NOT NULL,
    CNSMR_ID        BIGINT       NOT NULL,
    TRDLN_ID        BIGINT,
    PUB_REC_ID      BIGINT,
    RSN_CD          VARCHAR(10)  NOT NULL,   -- NOTMINE, WRONGBAL, WRONGSTS, PAIDOFF, FRAUD
    CHNL_CD         CHAR(3)      NOT NULL,   -- WEB, TEL, PST
    RCVD_TS         TIMESTAMP    NOT NULL,
    SLA_DUE_DT      DATE         NOT NULL,
    STS_CD          VARCHAR(10)  NOT NULL,   -- OPEN, REFERRED, CLOSED
    OUTCOME_CD      VARCHAR(10),             -- AMEND, DELETE, NOCHANGE
    RSLVD_TS        TIMESTAMP,
    RSLVD_BY        VARCHAR(8),
    CONSTRAINT PK_DISPUTE_CASE PRIMARY KEY (DSPT_ID),
    CONSTRAINT FK_DSPT_CNSMR FOREIGN KEY (CNSMR_ID) REFERENCES CONSUMER (CNSMR_ID),
    CONSTRAINT FK_DSPT_TRDLN FOREIGN KEY (TRDLN_ID) REFERENCES ACCOUNT_TRADELINE (TRDLN_ID),
    CONSTRAINT FK_DSPT_OPR FOREIGN KEY (RSLVD_BY) REFERENCES OPERATOR (OPR_ID)
);
CREATE INDEX IX_DSPT_CNSMR ON DISPUTE_CASE (CNSMR_ID);

CREATE TABLE DISPUTE_EVENT (
    DSPT_EVT_ID     BIGINT       NOT NULL,
    DSPT_ID         BIGINT       NOT NULL,
    EVT_TYP_CD      VARCHAR(20)  NOT NULL,
    EVT_TS          TIMESTAMP    NOT NULL,
    OPR_ID          VARCHAR(8),
    NOTE_TXT        VARCHAR(1000),
    CONSTRAINT PK_DISPUTE_EVENT PRIMARY KEY (DSPT_EVT_ID),
    CONSTRAINT FK_DEVT_DSPT FOREIGN KEY (DSPT_ID) REFERENCES DISPUTE_CASE (DSPT_ID)
);

CREATE TABLE DISPUTE_CORRESPONDENCE (
    CORR_ID         BIGINT       NOT NULL,
    DSPT_ID         BIGINT       NOT NULL,
    LTR_TMPL_CD     VARCHAR(10)  NOT NULL,   -- ACK01, RES01, RES02
    SENT_TS         TIMESTAMP    NOT NULL,
    CHNL_CD         CHAR(3)      NOT NULL,
    CONSTRAINT PK_DISPUTE_CORRESPONDENCE PRIMARY KEY (CORR_ID),
    CONSTRAINT FK_CORR_DSPT FOREIGN KEY (DSPT_ID) REFERENCES DISPUTE_CASE (DSPT_ID)
);

-- Disputed items are suppressed from scoring while the case is open.
ALTER TABLE ACCOUNT_TRADELINE ADD COLUMN DSPT_FLG CHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE PUBLIC_RECORD ADD COLUMN DSPT_FLG CHAR(1) DEFAULT 'N' NOT NULL;
